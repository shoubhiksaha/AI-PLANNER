// Long-press shortcuts on the Android app icon. Each opens an aiplanner:// link that App.js
// hands to the page (parseAppLink in bridge.js). Icons are the web app's own (Lucide) glyphs.
const fs = require('fs');
const path = require('path');
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withStringsXml,
} = require('expo/config-plugins');

const SHORTCUTS = [
  {
    id: 'scan',
    short: 'Scan a page',
    long: 'Scan a planner page',
    // i-scan-line
    paths: ['M3 7V5a2 2 0 0 1 2-2h2', 'M17 3h2a2 2 0 0 1 2 2v2', 'M21 17v2a2 2 0 0 1-2 2h-2', 'M7 21H5a2 2 0 0 1-2-2v-2', 'M7 12h10'],
  },
  {
    id: 'history',
    short: 'Sync history',
    long: 'Sync history',
    // i-history
    paths: ['M3 12a9 9 0 1 0 9-9 9.75 9.75 0 0 0-6.74 2.74L3 8', 'M3 3v5h5', 'M12 7v5l4 2'],
  },
  {
    id: 'reports',
    short: 'Last 30 days',
    long: 'Your last 30 days',
    // i-chart-column
    paths: ['M3 3v16a2 2 0 0 0 2 2h16', 'M18 17V9', 'M13 17V5', 'M8 17v-3'],
  },
];

const BACKGROUND = '#F2F4F3';
const GLYPH = '#0A0A0A';

const drawableName = (id) => `shortcut_${id}`;

function iconXml({ paths }) {
  const strokes = paths
    .map((d) => `      <path android:pathData="${d}" android:strokeColor="${GLYPH}" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />`)
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAppShortcuts.js -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp" android:height="48dp" android:viewportWidth="48" android:viewportHeight="48">
  <path android:pathData="M24 2a22 22 0 1 1 0 44a22 22 0 1 1 0 -44z" android:fillColor="${BACKGROUND}" />
  <group android:translateX="12" android:translateY="12">
${strokes}
  </group>
</vector>
`;
}

function shortcutsXml(packageName) {
  const items = SHORTCUTS.map((s) => `  <shortcut
      android:shortcutId="${s.id}"
      android:enabled="true"
      android:icon="@drawable/${drawableName(s.id)}"
      android:shortcutShortLabel="@string/shortcut_${s.id}_short"
      android:shortcutLongLabel="@string/shortcut_${s.id}_long">
    <intent
        android:action="android.intent.action.VIEW"
        android:data="aiplanner://${s.id}"
        android:targetPackage="${packageName}"
        android:targetClass="${packageName}.MainActivity" />
  </shortcut>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAppShortcuts.js -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${items}
</shortcuts>
`;
}

const withShortcutFiles = (config) =>
  withDangerousMod(config, ['android', (cfg) => {
    const res = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res');
    fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
    fs.mkdirSync(path.join(res, 'drawable'), { recursive: true });
    fs.writeFileSync(path.join(res, 'xml/shortcuts.xml'), shortcutsXml(cfg.android.package));
    for (const s of SHORTCUTS) {
      fs.writeFileSync(path.join(res, `drawable/${drawableName(s.id)}.xml`), iconXml(s));
    }
    return cfg;
  }]);

const withShortcutStrings = (config) =>
  withStringsXml(config, (cfg) => {
    for (const s of SHORTCUTS) {
      for (const [suffix, value] of [['short', s.short], ['long', s.long]]) {
        cfg.modResults = AndroidConfig.Strings.setStringItem(
          [{ $: { name: `shortcut_${s.id}_${suffix}`, translatable: 'false' }, _: value }],
          cfg.modResults,
        );
      }
    }
    return cfg;
  });

const withShortcutMetaData = (config) =>
  withAndroidManifest(config, (cfg) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);
    const metaData = (activity['meta-data'] || []).filter((m) => m.$['android:name'] !== 'android.app.shortcuts');
    metaData.push({ $: { 'android:name': 'android.app.shortcuts', 'android:resource': '@xml/shortcuts' } });
    activity['meta-data'] = metaData;
    return cfg;
  });

module.exports = (config) => withShortcutMetaData(withShortcutStrings(withShortcutFiles(config)));
module.exports.SHORTCUTS = SHORTCUTS;
