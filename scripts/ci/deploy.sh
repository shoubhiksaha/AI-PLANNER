#!/usr/bin/env bash
# ==============================================================================
# AI Planner — environment deploy (run by GitHub Actions only)
#
# Usage: deploy.sh <staging|production>
#
# Both environments live in Firebase project ai-planner-project-467800:
#   production → Firestore "(default)", functions us-central1 (codebase "default"),
#                Hosting site ai-planner-project-467800 (planner.analogdigital.tech)
#   staging    → Firestore "staging",   functions asia-south1 (codebase "staging"),
#                Hosting site ai-planner-staging (ai-planner-staging.web.app)
#
# The .firebaserc alias (staging|production) selects functions/.env.<alias>, so each
# environment's functions read their own database, region and URLs. Staging deploys use
# firebase.staging.json, generated from firebase.json so headers and rewrites never drift.
#
# Optional GitHub environment variables:
#   FIREBASE_API_KEY, FIREBASE_APP_ID, FIREBASE_MESSAGING_SENDER_ID, FIREBASE_AUTH_DOMAIN
#   APP_CHECK_SITE_KEY  reCAPTCHA Enterprise site key; empty = App Check off in the client
# Auth: Workload Identity (google-github-actions/auth) or FIREBASE_TOKEN env.
# ==============================================================================
set -euo pipefail

ENVIRONMENT="${1:?usage: deploy.sh <staging|production>}"
PROJECT_ID="ai-planner-project-467800"

case "$ENVIRONMENT" in
    staging)
        DATABASE_ID="staging"
        REGION="asia-south1"
        HOSTING_URL="https://ai-planner-staging.web.app"
        DEFAULT_AUTH_DOMAIN="${PROJECT_ID}.firebaseapp.com"
        CONFIG_FILE="firebase.staging.json"
        ;;
    production)
        DATABASE_ID="(default)"
        REGION="us-central1"
        HOSTING_URL="https://planner.analogdigital.tech"
        DEFAULT_AUTH_DOMAIN="planner.analogdigital.tech"
        CONFIG_FILE="firebase.json"
        ;;
    *)
        echo "Unknown environment: $ENVIRONMENT" >&2
        exit 2
        ;;
esac

if [ "${GITHUB_ACTIONS:-}" != "true" ]; then
    echo "❌ deploy.sh only runs inside GitHub Actions. Push to a branch instead (see docs/RELEASE_FLOW.md)." >&2
    exit 1
fi

if [ -z "${GOOGLE_APPLICATION_CREDENTIALS:-}" ] && [ -z "${FIREBASE_TOKEN:-}" ]; then
    echo "❌ No deploy credentials. Configure WIF_PROVIDER/SA_EMAIL (preferred) or FIREBASE_TOKEN on the '$ENVIRONMENT' environment." >&2
    exit 1
fi

# The functions env file must agree with this script, or functions would read the wrong database.
ENV_FILE="functions/.env.${ENVIRONMENT}"
grep -qx "FIRESTORE_DATABASE_ID=${DATABASE_ID}" "$ENV_FILE" || { echo "❌ $ENV_FILE must set FIRESTORE_DATABASE_ID=${DATABASE_ID}" >&2; exit 1; }
grep -qx "FUNCTIONS_REGION=${REGION}" "$ENV_FILE" || { echo "❌ $ENV_FILE must set FUNCTIONS_REGION=${REGION}" >&2; exit 1; }
grep -qx "APP_ENVIRONMENT=${ENVIRONMENT}" "$ENV_FILE" || { echo "❌ $ENV_FILE must set APP_ENVIRONMENT=${ENVIRONMENT}" >&2; exit 1; }

if [ "$ENVIRONMENT" = "staging" ]; then
    node scripts/ci/firebase-config.js staging
    # The staging database is created once; later deploys find it.
    if ! firebase firestore:databases:get "$DATABASE_ID" --project "$ENVIRONMENT" >/dev/null 2>&1; then
        echo "ℹ️  Creating Firestore database '$DATABASE_ID' (nam5)"
        firebase firestore:databases:create "$DATABASE_ID" --location nam5 --project "$ENVIRONMENT"
    fi
else
    node scripts/ci/firebase-config.js production
fi

API_KEY="${FIREBASE_API_KEY:-}"
APP_ID="${FIREBASE_APP_ID:-}"
SENDER_ID="${FIREBASE_MESSAGING_SENDER_ID:-}"
AUTH_DOMAIN="${FIREBASE_AUTH_DOMAIN:-$DEFAULT_AUTH_DOMAIN}"

if [ -z "$API_KEY" ] || [ -z "$APP_ID" ] || [ -z "$SENDER_ID" ]; then
    echo "ℹ️  Reading web app config from Firebase project $PROJECT_ID"
    SDK_JSON="$(firebase apps:sdkconfig WEB ${APP_ID:+"$APP_ID"} --project "$ENVIRONMENT" --json)"
    CFG="$(printf '%s' "$SDK_JSON" | jq -c '.result.sdkConfig // empty')"
    if [ -z "$CFG" ]; then
        # Older CLI output: config only inside fileContents.
        CFG="$(printf '%s' "$SDK_JSON" | jq -r '.result.fileContents' | sed -n '/{/,/}/p' | tr -d '\n' | sed -E 's/^[^{]*//; s/\)[^}]*$//')"
    fi
    CFG_PROJECT="$(printf '%s' "$CFG" | jq -r '.projectId // empty')"
    if [ "$CFG_PROJECT" != "$PROJECT_ID" ]; then
        echo "❌ Firebase returned config for '$CFG_PROJECT', expected '$PROJECT_ID'." >&2
        exit 1
    fi
    API_KEY="${API_KEY:-$(printf '%s' "$CFG" | jq -r '.apiKey')}"
    APP_ID="${APP_ID:-$(printf '%s' "$CFG" | jq -r '.appId')}"
    SENDER_ID="${SENDER_ID:-$(printf '%s' "$CFG" | jq -r '.messagingSenderId')}"
fi

for v in API_KEY APP_ID SENDER_ID; do
    if [ -z "${!v}" ] || [ "${!v}" = "null" ]; then
        echo "❌ Missing $v for $ENVIRONMENT." >&2
        exit 1
    fi
done

cat > public/env-config.js <<EOF
// Generated by scripts/ci/deploy.sh for ${ENVIRONMENT} — do not edit in the deployed bundle.
window.__ENV_CONFIG__ = {
    apiKey: "${API_KEY}",
    authDomain: "${AUTH_DOMAIN}",
    projectId: "${PROJECT_ID}",
    storageBucket: "${PROJECT_ID}.firebasestorage.app",
    messagingSenderId: "${SENDER_ID}",
    appId: "${APP_ID}",
    environment: "${ENVIRONMENT}",
    hostingUrl: "${HOSTING_URL}",
    firestoreDatabaseId: "${DATABASE_ID}",
    functionsRegion: "${REGION}",
    functionsBaseUrl: "https://${REGION}-${PROJECT_ID}.cloudfunctions.net",
    appCheckSiteKey: "${APP_CHECK_SITE_KEY:-}"
};
EOF

echo "✅ env-config.js written for $ENVIRONMENT (database ${DATABASE_ID}, region ${REGION})"
firebase deploy --project "$ENVIRONMENT" --config "$CONFIG_FILE" --non-interactive
